"""Export the validation-selected shadow model without reselecting on held-out results."""
import argparse
from collections import defaultdict
from datetime import date
import json
from pathlib import Path

from research.data import ALIASES, load_seasons
from research.models import LearnedPoisson


def export_elo(matches, cutoff, settings):
    by_day = defaultdict(list)
    for match in matches:
        if match.day < cutoff:
            by_day[match.day].append(match)
    ratings, season, count = {}, None, 0
    for day in sorted(by_day):
        games = by_day[day]
        if games[0].season != season:
            if season is not None:
                ratings = {team: 1500+(value-1500)*.85 for team,value in ratings.items()}
            season = games[0].season
        changes = defaultdict(float)
        for match in games:
            difference = ratings.get(match.home,1500.)-ratings.get(match.away,1500.)+settings['home_advantage']
            expectation = 1/(1+10**(-difference/400))
            actual = 1. if match.outcome==0 else .5 if match.outcome==1 else 0.
            movement = settings['k']*(actual-expectation)
            changes[match.home] += movement
            changes[match.away] -= movement
            count += 1
        for team,change in changes.items():
            ratings[team] = ratings.get(team,1500.)+change
    return {'parameters':settings,'ratings':ratings,'as_of':cutoff.isoformat(),'training_games':count,
            'latest_training_date':max(by_day).isoformat()}


def export(data_dir, experiment_dir, output, cutoff):
    experiment_dir=Path(experiment_dir)
    selected=json.loads((experiment_dir/'selection.json').read_text())
    summary=json.loads((experiment_dir/'summary.json').read_text())
    matches,_=load_seasons(range(2015,2027),data_dir)
    glm=LearnedPoisson(**selected['glm']).fit(matches,cutoff).export()
    model={'model_version':'ensemble-v2-experimental-0.1','status':'experimental','as_of':cutoff.isoformat(),
           'glm_weight':selected['glm_weight'],'glm':glm,'elo':export_elo(matches,cutoff,selected['elo']),
           'aliases':ALIASES,'features_used':['past_match_results','opponent_strength','home_advantage'],
           'news_used_in_probabilities':False,'promoted_to_default':False,
           'benchmark':{'period':'2025/26','common_fixtures':summary['held_out_common_targets'],
                        'metrics':summary['metrics_common']['candidate'],'base_metrics':summary['metrics_common']['base'],
                        'v1_metrics':summary['metrics_common']['v1'],
                        'protocol':'chronological validation selection; common held-out fixtures; prospective check still required',
                        'note':'Metrics evaluate rolling historical fits, not a single set of current team strengths.'}}
    output=Path(output);output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('// Generated by research.export_model from the persisted validation selection.\nexport default '+json.dumps(model,ensure_ascii=False,separators=(',',':'))+';\n')
    output.with_suffix('.json').write_text(json.dumps(model,ensure_ascii=False,indent=2))
    return model


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--data-dir',type=Path,required=True)
    parser.add_argument('--experiment-dir',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--cutoff',type=date.fromisoformat,required=True)
    args=parser.parse_args()
    model=export(args.data_dir,args.experiment_dir,args.output,args.cutoff)
    print('Exported',model['model_version'],'as of',model['as_of'],'GLM weight',model['glm_weight'])
