#!/usr/bin/env python3
"""Bundle explicitly referenced public site text assets for Worker /app/ hosting."""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'worker/site-assets.mjs'
MAX_BYTES = 1024 * 1024
MIME = {'.html':'text/html; charset=utf-8', '.css':'text/css; charset=utf-8',
        '.js':'text/javascript; charset=utf-8'}
IMPORT = re.compile(r'''\b(?:import|export)\s+(?:[^;\n]*?\s+from\s*)?['"]([^'"]+)['"]|\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)''')


def public_name(reference: str) -> str | None:
    parsed = urlsplit(reference)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return None
    path = unquote(parsed.path)
    if path.startswith('./'):
        path = path[2:]
    if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9_-]*\.(?:css|js)', path):
        raise ValueError('Only root public CSS/JS references may be bundled: ' + reference)
    return path


class References(HTMLParser):
    def __init__(self):
        super().__init__()
        self.names = set()

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        reference = values.get('src') if tag == 'script' else (
            values.get('href') if tag == 'link' and 'stylesheet' in values.get('rel', '').split() else None)
        if reference:
            name = public_name(reference)
            if name:
                self.names.add(name)


def collect_assets(root: Path = ROOT) -> dict[str, dict[str, str]]:
    root = root.resolve()
    html = (root / 'index.html').read_text(encoding='utf-8')
    parser = References()
    parser.feed(html)
    sources = {'index.html':html}
    todo = sorted(parser.names)
    while todo:
        name = todo.pop(0)
        if name in sources:
            continue
        path = root / name
        if path.resolve().parent != root or not path.is_file():
            raise ValueError('Missing or non-public asset: ' + name)
        body = path.read_text(encoding='utf-8')
        sources[name] = body
        if path.suffix == '.js':
            for match in IMPORT.finditer(body):
                reference = match.group(1) or match.group(2)
                if not reference.startswith('.'):
                    raise ValueError('Browser imports must be relative public assets: ' + reference)
                imported = public_name(reference)
                if imported and imported not in sources:
                    todo.append(imported)
    assets = {'/app/':{'body':html, 'contentType':MIME['.html']}}
    for name in sorted(sources):
        assets['/app/' + name] = {'body':sources[name], 'contentType':MIME[Path(name).suffix]}
    if sum(len(item['body'].encode('utf-8')) for item in assets.values()) > MAX_BYTES:
        raise ValueError('Public site bundle exceeds 1 MiB')
    return assets


def render_module(root: Path = ROOT) -> str:
    data = json.dumps(collect_assets(root), ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    data = data.replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return ('// Generated by scripts/build_site.py; public site files only.\n'
            'const assets = Object.freeze(' + data + ');\n'
            'export function getSiteAsset(path) {\n'
            '  return Object.hasOwn(assets,path) ? assets[path] : null;\n'
            '}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the generated bundle differs from source')
    args = parser.parse_args()
    source = render_module()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != source:
            parser.exit(1, 'Public site bundle is stale; run python3 scripts/build_site.py\n')
        print('Public site bundle is current.')
    else:
        OUTPUT.write_text(source, encoding='utf-8')
        print(f'Bundled {len(collect_assets())} public routes ({len(source.encode("utf-8"))} bytes).')


if __name__ == '__main__':
    main()
